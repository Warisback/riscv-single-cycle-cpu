#!/usr/bin/env python3
"""immgen_adv_merge.py: pair each assembled word with the immediate we asked for.

  usage: immgen_adv_merge.py <text.bin> <immgen_adv.expect> <vectors.hex>

<text.bin> is the raw .text section from objcopy -O binary (little-endian words).
Checks before writing anything:
  - one 32-bit word per requested instruction (the assembler did not expand or
    drop anything, e.g. no far-branch rewrite);
  - every word has the major opcode of the mnemonic we wrote.
Vector line format ($readmemh, 72 bits, '_' is only a separator):
  IIIIIIII_K_S_EEEEEEEE   instr, kind (0 directed, 1 random), imm_src, expected
The last line is the sentinel 00000000_f_f_00000000.
"""
import struct
import sys


def main():
    if len(sys.argv) != 4:
        print(__doc__)
        sys.exit(2)
    data = open(sys.argv[1], "rb").read()
    expect = [line.rstrip("\n").split(" ", 4) for line in open(sys.argv[2])]
    if len(data) != 4 * len(expect):
        print("immgen_adv_merge: %d bytes of code for %d instructions" % (len(data), len(expect)))
        sys.exit(1)
    words = struct.unpack("<%dI" % len(expect), data)
    bad = 0
    with open(sys.argv[3], "w") as f:
        f.write("// generated by tools/immgen_adv_merge.py: instr_kind_immsrc_expected\n")
        for w, (kind, src, value, opcode, text) in zip(words, expect):
            if (w & 0x7F) != int(opcode, 16):
                bad += 1
                print("immgen_adv_merge: opcode mismatch %08x for '%s'" % (w, text))
            f.write("%08x_%x_%x_%s  // %s\n" % (w, int(kind), int(src), value, text))
        f.write("00000000_f_f_00000000  // sentinel: end of vectors\n")
    if bad:
        sys.exit(1)
    print("immgen_adv_merge: %d vectors -> %s" % (len(expect), sys.argv[3]))


if __name__ == "__main__":
    main()
